import { createHash } from 'node:crypto';
import { Octokit } from '@octokit/rest';
import type { Explanation, Finding, Patch, VerifyResult } from '@payclinic/contracts';
import { applyEditsToString, checkEditsSafety, type ProjectsRepo, type Repos } from '@payclinic/core';

/** Raised when a finding may not be turned into a pull request. */
export class PrNotAllowedError extends Error {
  constructor(reason: string) {
    super(`Pull request is not allowed: ${reason}`);
    this.name = 'PrNotAllowedError';
  }
}

/** The minimal GitHub API surface the open-PR flow needs (Octokit-compatible). */
export interface GitHubLike {
  getRef(params: {
    owner: string;
    repo: string;
    ref: string;
  }): Promise<{ data: { object: { sha: string } } }>;
  createRef(params: { owner: string; repo: string; ref: string; sha: string }): Promise<unknown>;
  getContent(params: {
    owner: string;
    repo: string;
    path: string;
    ref: string;
  }): Promise<{ data: { content?: string; encoding?: string; type?: string } }>;
  createOrUpdateFileContents(params: {
    owner: string;
    repo: string;
    path: string;
    branch: string;
    message: string;
    content: string;
  }): Promise<unknown>;
  createPullRequest(params: {
    owner: string;
    repo: string;
    title: string;
    head: string;
    base: string;
    body: string;
  }): Promise<{ data: { html_url: string } }>;
}

/** Wraps Octokit with the minimal GitHubLike interface. The token is kept inside the client. */
export function createGitHubClient(token: string): GitHubLike {
  const octokit = new Octokit({ auth: token });
  return {
    getRef: (params) => octokit.git.getRef(params),
    createRef: (params) => octokit.git.createRef(params),
    getContent: async (params) => {
      const response = await octokit.repos.getContent(params);
      // The API returns a union (file/dir/symlink/array); callers narrow it.
      return { data: response.data as { content?: string; encoding?: string; type?: string } };
    },
    createOrUpdateFileContents: (params) => octokit.repos.createOrUpdateFileContents(params),
    createPullRequest: (params) => octokit.pulls.create(params),
  };
}

/** Replaces the GitHub token in an error message so it can never leak into logs. */
function sanitize(error: unknown, token: string): Error {
  const message = error instanceof Error ? error.message : String(error);
  const clean = token === '' ? message : message.split(token).join('[redacted]');
  return new Error(clean);
}

function shortId(findingId: string): string {
  return createHash('sha256').update(findingId).digest('hex').slice(0, 7);
}

function decodeBase64(content: string | undefined): string {
  if (content === undefined) throw new Error('GitHub returned no file content');
  return Buffer.from(content, 'base64').toString('utf8');
}

function prBody(
  finding: Finding,
  explanation: Explanation | null,
  patch: Patch,
  verify: VerifyResult | null,
  now: () => Date,
): string {
  const lines: string[] = [];
  lines.push('## PayClinic fix');
  lines.push('');
  lines.push(`Finding: **${finding.title}** (${finding.severity}, ${finding.scenarioKey}).`);
  lines.push('');
  if (explanation) {
    lines.push('### Root cause');
    lines.push(explanation.rootCause);
    lines.push('');
    lines.push('### Impact');
    lines.push(explanation.impact);
    lines.push('');
    lines.push('### Fix');
    lines.push(explanation.fixSummary);
    lines.push('');
  }
  lines.push('### Diff');
  lines.push('```diff');
  lines.push(patch.diff);
  lines.push('```');
  lines.push('');
  if (verify) {
    lines.push(
      `### Verification: ${verify.verified ? 'verified' : 'not verified'} ` +
        `(applied=${verify.applied}, started=${verify.started}, ` +
        `invariants=${verify.invariantPassed}, tests=${verify.testsPassed ?? 'not run'})`,
    );
    lines.push('');
  }
  lines.push(
    `> Generated by PayClinic on ${now().toISOString()}. The patch was produced and verified ` +
      `against the local PayPal **sandbox** simulator only; no live PayPal credentials or ` +
      `production systems were touched. Review the diff before merging.`,
  );
  return lines.join('\n');
}

export interface OpenPrDeps {
  github: GitHubLike;
  repos: Repos;
  projectsRepo?: ProjectsRepo;
  allowedPrefix?: string;
  owner: string;
  repo: string;
  baseBranch: string;
  now: () => Date;
  /** Used only to redact the token out of error messages; never sent anywhere. */
  token?: string;
}

/**
 * Creates the `openPr(findingId)` function: verifies the finding, applies the
 * patch edits to the base branch content (exactly-once rules from
 * TECH_DESIGN §8), commits them on a fresh branch and opens a pull request.
 */
export function createOpenPr(deps: OpenPrDeps): (findingId: string) => Promise<{ prUrl: string }> {
  const { github, repos, owner, repo, baseBranch, now } = deps;

  return async (findingId: string): Promise<{ prUrl: string }> => {
    try {
      const finding = repos.getFinding(findingId);
      if (!finding) throw new PrNotAllowedError(`finding ${findingId} does not exist`);
      const patch = repos.getPatchForFinding(findingId);
      if (finding.state !== 'verified') {
        throw new PrNotAllowedError(`finding ${findingId} is ${finding.state}, not verified`);
      }
      if (!patch) throw new PrNotAllowedError(`finding ${findingId} has no patch`);

      let allowedPrefix = deps.allowedPrefix;
      if (!allowedPrefix && deps.projectsRepo) {
        const run = repos.getRun(finding.runId);
        if (run?.projectId) {
          const project = deps.projectsRepo.getProject(run.projectId);
          if (project && project.kind === 'remote' && project.sourceRoot) {
            allowedPrefix = project.sourceRoot;
          }
        }
      }

      const safety = checkEditsSafety(patch.edits, {
        ...(allowedPrefix ? { allowedPrefix } : {}),
      });
      if (!safety.ok) throw new PrNotAllowedError(safety.reason);

      const explanation = repos.getExplanation(findingId);
      const verify = repos.getVerifyForPatch(patch.id);

      // Read and apply all edits against the BASE branch content first: any
      // failure here aborts before a branch or commit is created.
      const edited = new Map<string, string>();
      const byFile = new Map<string, typeof patch.edits>();
      for (const edit of patch.edits) {
        const existing = byFile.get(edit.file);
        if (existing) existing.push(edit);
        else byFile.set(edit.file, [edit]);
      }
      for (const [file, fileEdits] of byFile) {
        const response = await github.getContent({ owner, repo, path: file, ref: baseBranch });
        if (response.data.type !== 'file') {
          throw new Error(`${file} on ${baseBranch} is not a file`);
        }
        const original = decodeBase64(response.data.content);
        edited.set(file, applyEditsToString(original, fileEdits, file));
      }

      const branch = `payclinic/fix-${finding.scenarioKey}-${shortId(findingId)}`;
      const base = await github.getRef({ owner, repo, ref: `heads/${baseBranch}` });
      await github.createRef({
        owner,
        repo,
        ref: `refs/heads/${branch}`,
        sha: base.data.object.sha,
      });

      const commitMessage = `fix(${finding.scenarioKey}): ${finding.title}`;
      for (const [file, content] of edited) {
        await github.createOrUpdateFileContents({
          owner,
          repo,
          path: file,
          branch,
          message: commitMessage,
          content: Buffer.from(content, 'utf8').toString('base64'),
        });
      }

      const pull = await github.createPullRequest({
        owner,
        repo,
        title: commitMessage,
        head: branch,
        base: baseBranch,
        body: prBody(finding, explanation, patch, verify, now),
      });
      return { prUrl: pull.data.html_url };
    } catch (error) {
      if (error instanceof PrNotAllowedError) throw error;
      throw sanitize(error, deps.token ?? '');
    }
  };
}

export interface OpenPrEnv {
  GITHUB_TOKEN?: string | undefined;
  GITHUB_REPO?: string | undefined;
  GITHUB_BASE_BRANCH?: string | undefined;
}

/**
 * Builds the API `openPr` function from the environment. Returns undefined
 * (route answers "GitHub is not configured") when the token or repo is missing.
 * The token never leaves this module.
 */
export function openPrFromEnv(
  env: OpenPrEnv,
  deps: { repos: Repos; projectsRepo?: ProjectsRepo },
): ((findingId: string) => Promise<{ prUrl: string }>) | undefined {
  const token = env.GITHUB_TOKEN;
  const repoFull = env.GITHUB_REPO;
  if (token === undefined || token === '' || repoFull === undefined || repoFull === '') {
    return undefined;
  }
  const slash = repoFull.indexOf('/');
  if (slash <= 0 || slash === repoFull.length - 1) return undefined;
  const owner = repoFull.slice(0, slash);
  const repo = repoFull.slice(slash + 1);
  const baseBranch = env.GITHUB_BASE_BRANCH ?? 'main';
  return createOpenPr({
    github: createGitHubClient(token),
    repos: deps.repos,
    projectsRepo: deps.projectsRepo,
    owner,
    repo,
    baseBranch,
    now: () => new Date(),
    token,
  });
}
